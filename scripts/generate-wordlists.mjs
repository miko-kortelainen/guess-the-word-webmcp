function wordsFrom(file) {
  return fs
    .readFileSync(file, "utf8")
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter(Boolean);
}

function isFiveLetter(w) {
  return /^[a-z]{5}$/.test(w) && /[aeiouy]/.test(w);
}

function formatTsArray(name, words) {
  const lines = [`export const ${name}: string[] = [`];
  const perLine = 12;
  for (let i = 0; i < words.length; i += perLine) {
    const chunk = words.slice(i, i + perLine).map((w) => `"${w}"`);
    lines.push(`  ${chunk.join(", ")},`);
  }
  lines.push(`];`, ``);
  return lines.join("\n");
}

function positionalScore(word, posFreq) {
  const seen = new Set();
  let score = 0;
  for (let i = 0; i < 5; i++) {
    const ch = word[i];
    if (seen.has(ch)) continue;
    seen.add(ch);
    score += posFreq[i].get(ch) ?? 0;
  }
  return score;
}

const rawAllowed = wordsFrom("/tmp/words-alpha.txt").filter(isFiveLetter);
const allowed = [...new Set(rawAllowed)].sort();
const allowedSet = new Set(allowed);

const ranked = [];
const seenRanked = new Set();
for (const line of fs.readFileSync("/tmp/count_1w.txt", "utf8").split(/\r?\n/)) {
  if (!line) continue;
  const w = line.split(/[\s\t]+/)[0].toLowerCase();
  if (!isFiveLetter(w) || !allowedSet.has(w) || seenRanked.has(w)) continue;
  if (EXCLUDED.has(w)) continue;
  seenRanked.add(w);
  ranked.push(w);
}

const TARGET_ANSWER_COUNT = 2200;
const answers = ranked.slice(0, TARGET_ANSWER_COUNT);
for (const w of PINNED) {
  if (!allowedSet.has(w)) {
    console.warn(`pinned word ${w} is not in allowed; skipping`);
    continue;
  }
  if (!answers.includes(w)) answers.push(w);
}

const posFreq = Array.from({ length: 5 }, () => new Map());
for (const word of answers) {
  for (let i = 0; i < 5; i++) {
    posFreq[i].set(word[i], (posFreq[i].get(word[i]) ?? 0) + 1);
  }
}
const openers = [...answers]
  .sort((a, b) => positionalScore(b, posFreq) - positionalScore(a, posFreq) || a.localeCompare(b))
  .slice(0, 8);

const banner = `// Generated by scripts/generate-wordlists.mjs. Do not edit by hand.\n`;

fs.writeFileSync(path.join(root, "src/data/answers.ts"), banner + formatTsArray("answers", answers));
fs.writeFileSync(path.join(root, "src/data/allowed.ts"), banner + formatTsArray("allowed", allowed));
fs.writeFileSync(
  path.join(root, "src/game/openers.ts"),
  banner +
    `/** Hardcoded first-move suggestions. All members are in \`answers\`. */\n` +
    `export const OPENERS: string[] = ${JSON.stringify(openers, null, 2)};\n`,
);

